CREATE TABLE IF NOT EXISTS public.seguimiento_coincidencias (
  id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  id_lead BIGINT NOT NULL REFERENCES public.leads(id_lead) ON DELETE CASCADE,
  id_propiedad INTEGER NOT NULL REFERENCES public.propiedades(id_propiedad) ON DELETE CASCADE,
  favorito BOOLEAN NOT NULL DEFAULT FALSE,
  contactado BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario, id_lead, id_propiedad)
);

CREATE TABLE IF NOT EXISTS public.historial_generaciones_coincidencias (
  id_generacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  generada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  total BIGINT NOT NULL,
  nuevos BIGINT NOT NULL,
  modificados BIGINT NOT NULL,
  retirados BIGINT NOT NULL,
  propiedades_nuevas BIGINT NOT NULL,
  propiedades_no_disponibles BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.coincidencias_retiradas (
  id_generacion BIGINT NOT NULL REFERENCES public.historial_generaciones_coincidencias(id_generacion) ON DELETE CASCADE,
  id_lead BIGINT NOT NULL,
  id_propiedad INTEGER NOT NULL,
  no_disponible BOOLEAN NOT NULL,
  PRIMARY KEY (id_generacion, id_lead, id_propiedad)
);

ALTER TABLE public.coincidencias
  ADD COLUMN IF NOT EXISTS nueva BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS propiedad_nueva BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_seguimiento_coincidencias_usuario
  ON public.seguimiento_coincidencias (id_usuario, favorito, contactado);
CREATE INDEX IF NOT EXISTS idx_coincidencias_propiedad_actual
  ON public.coincidencias (id_propiedad) WHERE version_calculo = 1;
CREATE INDEX IF NOT EXISTS idx_coincidencias_retiradas_pareja
  ON public.coincidencias_retiradas (id_lead, id_propiedad, id_generacion DESC);
