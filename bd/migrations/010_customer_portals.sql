BEGIN;

-- Agrega el historial de seguimiento y las notificaciones del equipo.
ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS id_propiedad_interes INTEGER
    REFERENCES public.propiedades(id_propiedad) ON DELETE SET NULL;

-- Guarda notas y tareas asignadas para dar continuidad a cada cliente.
CREATE TABLE IF NOT EXISTS public.seguimientos_clientes (
  id_seguimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente INTEGER NOT NULL REFERENCES public.clientes(id_cliente) ON DELETE CASCADE,
  id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE RESTRICT,
  asignado_a INTEGER REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('nota', 'tarea')),
  contenido TEXT NOT NULL CHECK (length(trim(contenido)) > 0),
  fecha_limite TIMESTAMPTZ,
  estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'completada')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT seguimientos_tarea_fecha CHECK (tipo <> 'tarea' OR fecha_limite IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_seguimientos_cliente_fecha
  ON public.seguimientos_clientes(id_cliente, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_seguimientos_usuario_fecha
  ON public.seguimientos_clientes(asignado_a, fecha_limite)
  WHERE estado = 'pendiente';

-- Conserva avisos por usuario y evita duplicados mediante una clave unica.
CREATE TABLE IF NOT EXISTS public.notificaciones (
  id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE CASCADE,
  dedupe_key VARCHAR(180) NOT NULL,
  titulo VARCHAR(180) NOT NULL,
  detalle TEXT NOT NULL,
  entidad VARCHAR(40) NOT NULL,
  entidad_id TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  leido_en TIMESTAMPTZ,
  UNIQUE (id_usuario, dedupe_key)
);

CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario_recientes
  ON public.notificaciones(id_usuario, creado_en DESC);

-- Define que documentos legales puede consultar cada cliente inquilino.
CREATE TABLE IF NOT EXISTS public.acceso_documentos_inquilino (
  id_cliente INTEGER NOT NULL REFERENCES public.clientes(id_cliente) ON DELETE CASCADE,
  id_documento BIGINT NOT NULL REFERENCES public.expedientes_legales(id_documento) ON DELETE CASCADE,
  otorgado_por INTEGER NOT NULL REFERENCES public.usuarios(id_usuario) ON DELETE RESTRICT,
  otorgado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_cliente, id_documento)
);

COMMIT;
