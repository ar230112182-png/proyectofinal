-- Registra solicitudes de reparacion vinculadas a inmuebles o contratos.
BEGIN;

CREATE TABLE IF NOT EXISTS public.solicitudes_mantenimiento (
  id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_propiedad INTEGER NOT NULL
    REFERENCES public.propiedades(id_propiedad) ON DELETE RESTRICT,
  id_renta INTEGER
    REFERENCES public.rentas(id_renta) ON DELETE SET NULL,
  solicitado_por INTEGER NOT NULL
    REFERENCES public.usuarios(id_usuario) ON DELETE RESTRICT,
  asignado_a INTEGER
    REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  titulo VARCHAR(180) NOT NULL,
  descripcion TEXT NOT NULL,
  prioridad VARCHAR(15) NOT NULL DEFAULT 'normal'
    CHECK (prioridad IN ('baja', 'normal', 'alta', 'urgente')),
  estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'en_proceso', 'completada', 'cancelada')),
  costo_estimado NUMERIC(15, 2)
    CHECK (costo_estimado IS NULL OR costo_estimado >= 0),
  costo_final NUMERIC(15, 2)
    CHECK (costo_final IS NULL OR costo_final >= 0),
  fecha_limite DATE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_mantenimiento_estado_fecha
  ON public.solicitudes_mantenimiento(estado, fecha_limite, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_mantenimiento_propiedad_fecha
  ON public.solicitudes_mantenimiento(id_propiedad, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_mantenimiento_asignado_estado
  ON public.solicitudes_mantenimiento(asignado_a, estado);

COMMIT;
